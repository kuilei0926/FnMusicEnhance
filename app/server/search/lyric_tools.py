import re

# 仅时间戳标签、无文本的空行（如 "[00:12.00]"），清理时去掉
_ONLY_TIMESTAMP_RE = re.compile(r"\[(\d{2}:)?\d{2}:\d{2}(?:\.\d{1,3})?\]")
_STRIP_CHARS = "﻿​‌‍⁠  \t"
_LRC_LINE_RE = re.compile(r"\[(\d{1,2}):(\d{2})(?:[.:](\d{1,3}))?\](.*)")


def cleanlrc(text):
    """规范化 LRC：统一换行、去首尾空白、去掉只有时间戳标签的空行。"""
    if not text:
        return ""
    lines = []
    for raw in re.sub(r"\r\n?", "\n", str(text)).split("\n"):
        line = raw.strip(_STRIP_CHARS).strip()
        if line and not _ONLY_TIMESTAMP_RE.fullmatch(line):
            lines.append(line)
    return "\n".join(lines)


def lrc_to_structured(lrc_text):
    """行级 LRC 文本 → structured 行数组（Lyrico 交换格式，每行一个整行文本）。

    每行 `[mm:ss.xx]text` → `[startMs, endMs, "text"]`（endMs 取 startMs）。
    """
    lines = []
    if not lrc_text:
        return lines
    for raw in lrc_text.split("\n"):
        m = _LRC_LINE_RE.match(raw.strip())
        if not m:
            continue
        minutes = int(m.group(1))
        seconds = int(m.group(2))
        start = (minutes * 60 + seconds) * 1000
        frac = m.group(3)
        if frac:
            scale = 100 if len(frac) == 1 else 10 if len(frac) == 2 else 1
            start += int(frac) * scale
        text = m.group(4).strip()
        if not text:
            continue
        lines.append([start, start, text])
    return lines


