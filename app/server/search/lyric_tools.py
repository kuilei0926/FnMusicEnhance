def convert_text(text, mode):
    """简繁转换：mode 为 simplifiedToTraditional / traditionalToSimplified / none。"""
    if not text or mode == "none":
        return text
    table = _S2T if mode == "simplifiedToTraditional" else _T2S
    return "".join(table.get(c, c) for c in text)


def apply_lyric_options(lines, convert="none", remove_blank=False, filter_rules=None):
    """对 structured 行数组应用客户端偏好：简繁转换 / 过滤规则 / 移除空行。

    词级行逐词转换并过滤；行级行整行处理。返回新的 structured 行数组。
    """
    rules = [r for r in (filter_rules or []) if isinstance(r, str) and r]
    out = []
    for item in lines:
        if not isinstance(item, list) or len(item) < 3:
            continue
        start, end = item[0], item[1]
        payload = item[2]
        if isinstance(payload, list):
            # 先用原始拼接文本判断过滤/空行（过滤规则按歌词原文匹配），再逐词转换
            full_text = "".join(
                str(w[2]) for w in payload if isinstance(w, list) and len(w) > 2
            )
            if remove_blank and not full_text.strip():
                continue
            if any(r in full_text for r in rules):
                continue
            words = []
            for w in payload:
                if not isinstance(w, list) or len(w) < 3:
                    continue
                ws, we, text = w
                words.append([ws, we, convert_text(str(text), convert)])
            if not words:
                continue
            out.append([start, end, words])
        else:
            text = str(payload)
            if remove_blank and not text.strip():
                continue
            if any(r in text for r in rules):
                continue
            out.append([start, end, convert_text(text, convert)])
    return out
